const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--enable-unsafe-swiftshader']});
 try {
 const page=await browser.newPage({viewport:{width:1500,height:1000},acceptDownloads:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.STUDIO_BASE_URL,{waitUntil:'networkidle'});
 await page.getByLabel('Open item files',{exact:true}).setInputFiles(path.join(__dirname,'Fixtures/Approved/ObstaclePusher4mLevel1.Item.Gbx'));
 await page.waitForFunction(()=>typedMotions.length===1);
 await page.getByRole('button',{name:'WaypointType, Gameplay & Kinematics',exact:true}).click();
 const panel=page.getByTestId('draw-motion-path');await panel.locator('summary').click();
 await page.locator('#pathRepeat').selectOption('Closed');
 await page.locator('#pathSpeed').fill('5');await page.locator('#pathSpeed').press('Tab');
 await page.locator('#pathCoordinates').fill('0 8 0\n20 8 0\n20 8 20');
 await page.getByRole('button',{name:'Use coordinates',exact:true}).click();
 await page.getByRole('button',{name:'Preview path',exact:true}).click();
 await page.waitForFunction(()=>!!drawPathDraft);
 const before=await page.evaluate(()=>JSON.stringify(currentPayload));
 const edit=page.getByTestId('path-segment-editor');
 await edit.getByLabel('Segment speed',{exact:true}).fill('2.5');await edit.getByLabel('Segment speed',{exact:true}).press('Tab');
 await page.waitForFunction(()=>drawPathDraft.plan.legs[0].moveMs===8000);
 assert.equal(await page.evaluate(()=>drawPathDraft.plan.legs[1].startMs),8000);
 await edit.getByLabel('Segment to X',{exact:true}).fill('30');await edit.getByLabel('Segment to X',{exact:true}).press('Tab');
 await page.waitForFunction(()=>drawPathDraft.plan.legs[0].delta.x===30);
 assert.equal(await page.evaluate(()=>drawPathDraft.plan.legs[1].delta.x),-10);
 assert.equal(await page.evaluate(()=>JSON.stringify(currentPayload)),before,'editing draft mutated item');
 await edit.getByLabel('Search Path segment',{exact:true}).fill('Segment 2:');
 const option=await edit.getByLabel('Path segment',{exact:true}).locator('option').allTextContents();
 await edit.getByLabel('Path segment',{exact:true}).selectOption({label:option.find(v=>v.startsWith('Segment 2:'))});
 await edit.getByLabel('Segment duration',{exact:true}).fill('3');await edit.getByLabel('Segment duration',{exact:true}).press('Tab');
 await page.waitForFunction(()=>drawPathDraft.plan.legs[1].moveMs===3000);
 const edited=await page.evaluate(()=>drawPathDraft.plan);
 const out=path.resolve(__dirname,'../../artifacts/path-collision');fs.mkdirSync(out,{recursive:true});
 const save=page.waitForEvent('download');await page.getByRole('button',{name:'Save route draft (.json)',exact:true}).click();
 await(await save).saveAs(path.join(out,'edited-route.motion-path.json'));
 await page.getByLabel('Load route draft',{exact:false}).setInputFiles(path.join(out,'edited-route.motion-path.json'));
 await page.waitForFunction(()=>drawPathDraft.plan.legs[1].moveMs===3000);
 assert.deepEqual(await page.evaluate(()=>drawPathDraft.plan),edited);
 await edit.screenshot({path:path.join(out,'route-editor.png')});
 await edit.getByRole('button',{name:'Apply edited route',exact:true}).click();
 await panel.getByText(/^Applied /).waitFor();
 const actual=await page.evaluate(plan=>{
   isPlaying=false;const motion=typedMotions.find(m=>(motionGroups.get(m.childPath)?.[0].children.length||0)>1);
   let p=new THREE.Vector3(plan.start.x,plan.start.y,plan.start.z);
   return plan.legs.map(l=>{const delta=new THREE.Vector3(l.delta.x,l.delta.y,l.delta.z);const target=p.clone().addScaledVector(delta,.5);p.add(delta);animTime=l.startMs+l.moveMs/2;applyTypedMotion();scene.updateMatrixWorld(true);return new THREE.Box3().setFromObject(motionGroups.get(motion.childPath)[0]).getCenter(new THREE.Vector3()).distanceTo(target);});
 },edited);
 assert.ok(actual.every(e=>e<.002),JSON.stringify(actual));
 const advanced=page.getByTestId('advanced-motion-constraints');await advanced.locator(':scope > summary').click();
 assert.equal(await advanced.locator('.motion-constraint').count(),1);
 await advanced.getByLabel('Search Motion constraint',{exact:true}).fill('Constraint 2');
 const values=await advanced.getByLabel('Motion constraint',{exact:true}).locator('option').allTextContents();
 await advanced.getByLabel('Motion constraint',{exact:true}).selectOption({label:values.find(v=>v.startsWith('Constraint 2'))});
 assert.equal(await advanced.locator('.motion-constraint').count(),1);
 await advanced.getByLabel('Rotation axis',{exact:true}).waitFor();
 await page.screenshot({path:path.join(out,'segment-controls.png')});
 assert.deepEqual(errors,[]);
 console.log('PASS per-segment speed/time, adjacent geometry, immutable draft, JSON roundtrip, search and single constraint editor');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
